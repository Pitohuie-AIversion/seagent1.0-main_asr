import requests
import json
import time
import uuid

BASE_URL = "http://127.0.0.1:8890"

def chat(session_id, message):
    print(f"\n💬 [User -> SEAgent] ({session_id})")
    print(f"   输入: {message}")
    t0 = time.time()
    try:
        resp = requests.post(f"{BASE_URL}/api/chat", json={"message": message, "session_id": session_id}, timeout=45)
        dt = time.time() - t0
        data = resp.json()
        reply = data.get("reply", "")
        phase = data.get("phase", "unknown")
        task_id = data.get("task_id")
        task_id_preview = data.get("task_id_preview")
        ui_state = data.get("ui_state", {})
        print(f"🤖 [SEAgent -> User] (耗时: {dt:.2f}s | Phase: {phase} | TaskId: {task_id or task_id_preview})")
        print(f"{reply}")
        return data
    except Exception as e:
        print(f"❌ 请求失败: {e}")
        return {}

